const _appleBase = {
  WatchFeature.ecg,
  WatchFeature.spo2,
  WatchFeature.gps,
  WatchFeature.nfcPay,
  WatchFeature.appStore,
};

Watch _apple(String id, String model, String chip, double score, int storage,
        int hours, int year, int minIos, double price,
        {Set<WatchFeature> extra = const {}, double ram = 1}) =>
    Watch(
      id: id,
      brand: 'Apple',
      model: model,
      os: WatchOs.watchOs,
      chip: chip,
      chipScore: score,
      ramGb: ram,
      storageGb: storage,
      batteryHours: hours,
      year: year,
      features: {..._appleBase, ...extra},
      worksWith: _ios,
      minIos: minIos,
      refPriceUsd: price,
    );

Watch _galaxy(String id, String model, String chip, double score, double ram,
        int hours, int year, int minAndroid, double price,
        {Set<WatchFeature> extra = const {}}) =>
    Watch(
      id: id,
      brand: 'Samsung',
      model: model,
      os: WatchOs.wearOs,
      chip: chip,
      chipScore: score,
      ramGb: ram,
      storageGb: 32,
      batteryHours: hours,
      year: year,
      features: {
        WatchFeature.ecg,
        WatchFeature.bloodPressure,
        WatchFeature.spo2,
        WatchFeature.gps,
        WatchFeature.nfcPay,
        WatchFeature.appStore,
        ...extra,
      },
      worksWith: _android,
      minAndroid: minAndroid,
      samsungOnly: const {WatchFeature.ecg, WatchFeature.bloodPressure},
      refPriceUsd: price,
    );

